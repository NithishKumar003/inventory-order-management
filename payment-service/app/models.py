import enum

from sqlalchemy import Column, DateTime, Enum, Integer, Numeric, String, UniqueConstraint
from sqlalchemy.sql import func

from app.database import Base


class PaymentStatus(str, enum.Enum):
    PENDING = "PENDING"
    SUCCESS = "SUCCESS"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class Payment(Base):
    __tablename__ = "payments"

    __table_args__ = (
        UniqueConstraint(
            "user_id",
            "idempotency_key",
            name="uq_payment_user_idempotency",
        ),
    )

    id = Column(Integer, primary_key=True, index=True)

    # The order this payment belongs to.
    order_id = Column(Integer, nullable=False, index=True)

    # The user who initiated the payment.
    user_id = Column(Integer, nullable=False, index=True)

    # Unique reference generated by our Payment Service.
    transaction_reference = Column(
        String(64),
        unique=True,
        nullable=False,
        index=True,
    )

    stripe_session_id = Column(
        String(255),
        unique=True,
        nullable=True,
        index=True,
    )

    # Prevents duplicate processing of the same payment request.
    idempotency_key = Column(String(100), nullable=False)

    amount = Column(Numeric(12, 2), nullable=False)

    status = Column(
        Enum(PaymentStatus),
        default=PaymentStatus.PENDING,
        nullable=False,
    )

    # Optional description of the simulated payment result.
    failure_reason = Column(String(250), nullable=True)

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
